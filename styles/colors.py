    _current_theme = "dark"

    @classmethod
    def available_themes(cls):
        return tuple(cls._THEMES.keys())

    @classmethod
    def current_theme(cls) -> str:
        return cls._current_theme

    @classmethod
    def is_dark(cls) -> bool:
        return cls.theme_scheme() == "dark"

    @classmethod
    def theme_label(cls, theme_name: str = None) -> str:
        theme = cls.normalize_theme(theme_name or cls._current_theme)
        meta = cls._THEME_META.get(theme, {})
        return str(meta.get("label") or theme.replace("_", " ").title())

    @classmethod
    def theme_scheme(cls, theme_name: str = None) -> str:
        theme = cls.normalize_theme(theme_name or cls._current_theme)
        meta = cls._THEME_META.get(theme, {})
        return str(meta.get("scheme") or "dark")

    @classmethod
    def theme_specs(cls):
        specs = []
        for name in cls._THEMES:
            meta = dict(cls._THEME_META.get(name, {}))
            meta["name"] = name
            meta.setdefault("label", name.replace("_", " ").title())
            meta.setdefault("scheme", "dark")
            specs.append(meta)
        return tuple(specs)

    @staticmethod
    def rgba(color_value: str, alpha: float) -> str:
        value = str(color_value or "").strip()
        if not value.startswith("#"):
            return value
        hex_value = value[1:]
        if len(hex_value) == 3:
            hex_value = "".join(ch * 2 for ch in hex_value)
        if len(hex_value) != 6:
            return value
        try:
            red = int(hex_value[0:2], 16)
            green = int(hex_value[2:4], 16)
            blue = int(hex_value[4:6], 16)
            alpha_value = max(0.0, min(1.0, float(alpha)))
        except Exception:
            return value
        alpha_text = f"{alpha_value:.3f}".rstrip("0").rstrip(".")
        return f"rgba({red}, {green}, {blue}, {alpha_text})"

    @classmethod
    def normalize_theme(cls, theme_name: str) -> str:
        theme = str(theme_name or "dark").strip().lower().replace("-", "_").replace(" ", "_")
        theme = cls._THEME_ALIASES.get(theme, theme)
        if theme in cls._THEMES:
            return theme
        for candidate, meta in cls._THEME_META.items():
            label_key = str(meta.get("label") or "").strip().lower().replace("-", "_").replace(" ", "_")
            if theme == label_key:
                return candidate
        return theme if theme in cls._THEMES else "dark"

    @classmethod
    def apply_theme(cls, theme_name: str) -> str:
        theme = cls.normalize_theme(theme_name)
        for token_name, value in cls._THEMES[theme].items():
            setattr(cls, token_name, value)
        cls._current_theme = theme
        return theme


