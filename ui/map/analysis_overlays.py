        "radius:Number(p.radius||6), color:String(p.color||'#4ade80'), weight:Number(p.weight||1), opacity:0.9,"
        "fill:true, fillColor:String(p.color||'#4ade80'), fillOpacity:Number(p.fill_opacity||0.35),"
