        "window.__replaceDynamicCoverage = function(payload){"
        "try{"
        "if(!window.L) return;"
        "var m = (typeof findMap === 'function') ? findMap() : null;"
        "if(!m) return;"
        "if(window.__dynCoverage){ try{ m.removeLayer(window.__dynCoverage); }catch(err){} }"
